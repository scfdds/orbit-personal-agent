import { writeFileSync } from 'node:fs';
import { OrbitStore } from '../src/server/store.ts';
import { seedEverydayShowcase } from '../src/server/showcases/everyday.ts';
import { seedAiNewsShowcase } from '../src/server/showcases/ai-news.ts';
import { DiscussionService } from '../src/server/discussion.ts';

const store = new OrbitStore(':memory:');
seedEverydayShowcase(store);
const { ids } = seedAiNewsShowcase(store, { fixtures: false });
try {
  await Promise.all(ids.map(async id => {
    const service = new DiscussionService(store, () => {});
    try {
      await service.schedule(id);
      const discussion = service.get(id);
      if (discussion.status !== 'ready') throw new Error(discussion.error || 'Turn summaries incomplete');
      console.log(id, discussion.turns.length, 'turns');
    } finally { await service.close(); }
  }));
  const turns = ids.flatMap(id => store.require('memories', id).discussion!.turns);
  writeFileSync('src/server/showcases/ai-news-turns.ts', '// Generated by DeepSeek from the authored AI news Q&A.\nimport type { TurnSummary } from "../../shared/types.ts";\nexport const aiNewsTurns: TurnSummary[] = ' + JSON.stringify(turns, null, 2) + ';\n');
} finally { store.close(); }
