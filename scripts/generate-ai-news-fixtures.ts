import { writeFileSync } from 'node:fs';
import { OrbitStore } from '../src/server/store.ts';
import { seedEverydayShowcase } from '../src/server/showcases/everyday.ts';
import { seedAiNewsShowcase } from '../src/server/showcases/ai-news.ts';
import { RecapService } from '../src/server/recap.ts';
import { TopicOverviewService } from '../src/server/topic-overview.ts';

const store = new OrbitStore(':memory:');
seedEverydayShowcase(store);
const { ids } = seedAiNewsShowcase(store, { fixtures: false });
const recap = new RecapService(store, () => {}), overview = new TopicOverviewService(store, () => {});
try {
  await Promise.all(ids.map(async id => {
    const result = await recap.refresh(id);
    if (!result) throw new Error(`No recap for ${id}`);
    console.log(id, result.nodes.length, 'points');
  }));
  const section = store.list('sections').find(s => s.name === 'AI 动态')!;
  const text = await overview.refresh(section.id);
  const recaps = Object.fromEntries(ids.map(id => [id, store.require('memories', id).recap]));
  writeFileSync('src/server/showcases/ai-news-fixtures.ts', '// Generated by DeepSeek from authored conversations, then editorially reviewed.\nimport type { ConversationRecap } from "../../shared/types.ts";\nexport const aiNewsRecaps: Record<string, ConversationRecap> = ' + JSON.stringify(recaps, null, 2) + ';\nexport const aiNewsOverview = ' + JSON.stringify(text) + ';\n');
  console.log('Saved AI news recaps and topic overview');
} finally { await recap.close(); await overview.close(); store.close(); }
